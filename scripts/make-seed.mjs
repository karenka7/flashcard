// Writes supabase/seed.sql: the built-in decks and their cards, taken from src/data/.
// Run after changing built-in cards:  node scripts/make-seed.mjs
import { writeFileSync } from "node:fs";
import { RN } from "../src/data/nclex.js";
import { ANAT } from "../src/data/anatomy.js";
import { MUSIC } from "../src/data/music.js";

const q = v => v == null || v === "" ? "null" : "'" + String(v).replace(/'/g, "''") + "'";
const j = v => v == null ? "null" : q(JSON.stringify(v)) + "::jsonb";

const describe = d => d.sub || (d.topics
  ? `Demo deck of ${d.cards.length} cards across ${Object.keys(d.topics).length} exam areas`
  : `Demo deck of ${d.cards.length} cards, ${d.cards.filter(c => c.imgQ || c.imgA).length} with diagrams`);

const decks = [RN, ANAT, MUSIC];
let sql = `-- Built-in decks and cards. Generated by scripts/make-seed.mjs from src/data/; don't edit by hand.
-- Safe to run again: existing rows are updated in place.

insert into public.decks (id, owner_id, name, description, color, topics, position) values
${decks.map((d, i) => `  (${q(d.id)}, null, ${q(d.name)}, ${q(describe(d))}, ${q(d.color)}, ${j(d.topics)}, ${i})`).join(",\n")}
on conflict (id) do update set name = excluded.name, description = excluded.description,
  color = excluded.color, topics = excluded.topics, position = excluded.position;
`;

for (const d of decks) {
  const rows = d.cards.map((c, i) => "  (" + [
    q(c.id), q(d.id), "null", i, q(c.kind || "recall"), q(c.t), q(c.q), q(c.a), q(c.why), q(c.src),
    j(c.opts), j(c.ans), q(c.imgQ), q(c.imgA), q(c.sndQ), q(c.sndA),
  ].join(", ") + ")");
  sql += `
-- ${d.name}: ${d.cards.length} cards
insert into public.cards (id, deck_id, owner_id, position, kind, topic, question, answer, explanation, source,
  options, correct, image_front, image_back, sound_front, sound_back) values
${rows.join(",\n")}
on conflict (id) do update set deck_id = excluded.deck_id, position = excluded.position, kind = excluded.kind,
  topic = excluded.topic, question = excluded.question, answer = excluded.answer, explanation = excluded.explanation,
  source = excluded.source, options = excluded.options, correct = excluded.correct,
  image_front = excluded.image_front, image_back = excluded.image_back,
  sound_front = excluded.sound_front, sound_back = excluded.sound_back,
  version = case when (cards.question, cards.answer, cards.explanation, cards.options, cards.correct)
                  is distinct from (excluded.question, excluded.answer, excluded.explanation, excluded.options, excluded.correct)
             then cards.version + 1 else cards.version end;
`;
}

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`supabase/seed.sql: ${decks.length} decks, ${decks.reduce((n, d) => n + d.cards.length, 0)} cards`);
